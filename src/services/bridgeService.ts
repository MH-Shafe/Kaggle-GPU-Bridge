export function loadStoredConfig(): ConnectionConfig {
  try {
    const raw = localStorage.getItem(CONFIG_STORAGE_KEY);
    if (raw) {
      return { ...DEFAULT_CONFIG, ...JSON.parse(raw) };
    }
  } catch (e) {
    console.error('Failed to load stored config', e);
  }
  return DEFAULT_CONFIG;
}

export function saveStoredConfig(cfg: ConnectionConfig): void {
  try {
    localStorage.setItem(CONFIG_STORAGE_KEY, JSON.stringify(cfg));
  } catch (e) {
    console.error('Failed to save config', e);
  }
}

/**
 * Secret redaction filter complying with Section 4.8 & 4.9.
 * Strips tokens, Bearer credentials, and API keys before outputting to logs.
 */
export function redactSecrets(text: string): string {
  if (!text) return '';
  return text
    .replace(/(token=)([a-zA-Z0-9_\-\.]{8,})/gi, '$1[REDACTED_TOKEN]')
    .replace(/(Bearer\s+)([a-zA-Z0-9_\-\.]{8,})/gi, '$1[REDACTED_SECRET]')
    .replace(/(api[_-]?key[\"']?\s*[:=]\s*[\"']?)([a-zA-Z0-9_\-\.]{8,})/gi, '$1[REDACTED_KEY]')
    .replace(/(eyJh[a-zA-Z0-9_\-]{20,})/g, '[REDACTED_JWT]');
}

